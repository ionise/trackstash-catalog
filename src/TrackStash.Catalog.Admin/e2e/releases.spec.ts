import { expect, test } from '@playwright/test'

const key = 'test-only-browser-key-not-a-production-secret'

test('browse catalog releases from menu and label-filtered tab with shared detail and track paging, read-only', async ({ page }) => {
  const writes: string[] = []
  const errors: string[] = []
  page.on('request', request => { if (request.url().includes('/api/v1/') && request.method() !== 'GET') writes.push(request.method()) })
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/admin/#/releases')
  await page.getByLabel('API key').fill(key)
  await page.getByRole('button', { name: 'Connect', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Releases', exact: true, level: 1 })).toBeVisible()
  await page.getByRole('textbox', { name: 'Search releases', exact: true }).fill('RELCAT001')
  const list = page.getByRole('table', { name: 'Catalog releases', exact: true })
  await expect(list.getByRole('row')).toHaveCount(2)
  await list.getByRole('link', { name: 'Fixture Catalog Release', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Fixture Catalog Release', exact: true, level: 1 })).toBeVisible()
  await expect(page.getByText(/Catalog number: RELCAT001; UPC: 012345/)).toBeVisible()
  const tracks = page.getByRole('table', { name: 'Catalog release tracks', exact: true })
  await expect(tracks.getByRole('row')).toHaveCount(26)
  await expect(tracks.getByRole('row').nth(1)).toContainText('Fixture Remix')
  const firstTrack = tracks.getByRole('row').nth(1)
  await expect(firstTrack).toContainText('Fixture Composer · Fixture Remix Act [unresolved compound]')
  await expect(firstTrack.getByRole('cell').nth(0)).toHaveText('1')
  await expect(firstTrack.getByRole('link', { name: 'Fixture Composer', exact: true })).toHaveCount(1)
  await expect(tracks.getByRole('columnheader', { name: 'Label', exact: true })).toHaveCount(0)
  await expect(firstTrack.getByRole('cell')).toHaveCount(3)
  await expect(tracks.getByRole('link', { name: 'Release Fixture Label', exact: true })).toHaveCount(0)
  await expect(page.getByRole('link', { name: 'Release Fixture Label (primary label)', exact: true })).toBeVisible()
  await expect(firstTrack.getByText('Official disc/track: ?/?', { exact: false })).not.toBeVisible()
  await firstTrack.getByRole('button', { name: 'Track details', exact: true }).click()
  await expect(firstTrack).toContainText('Source position: 26')
  await expect(firstTrack).toContainText('Official disc/track: ?/?')
  await page.getByRole('button', { name: 'Next page', exact: true }).click()
  await expect(tracks.getByRole('row')).toHaveCount(2)
  await expect(tracks).toContainText('Catalog Track 26')
  await expect(tracks.getByRole('row').nth(1).getByRole('cell').nth(0)).toHaveText('26')
  const beatport = page.getByRole('link', { name: /Beatport: Release 999001/ })
  await expect(beatport).toHaveAttribute('href', 'https://www.beatport.com/release/fixture-catalog-release/999001')
  await expect(beatport.locator('svg path')).toHaveCount(1)
  await beatport.hover()
  await expect(page.getByRole('tooltip', { name: /Open Beatport:/ })).toContainText('in a new tab')
  await expect(page.getByRole('button', { name: 'Manage release artwork', exact: true })).toHaveCount(0)
  await page.getByRole('link', { name: 'Release Fixture Label (primary label)', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Release Fixture Label', exact: true })).toBeVisible()
  const labelList = page.getByRole('table', { name: 'Label releases', exact: true })
  await expect(labelList.getByRole('row')).toHaveCount(2)
  await expect(labelList.getByRole('columnheader', { name: 'Primary artist', exact: true })).toBeVisible()
  await expect(labelList.getByRole('columnheader', { name: 'Label', exact: true })).toHaveCount(0)
  await expect(labelList.getByRole('row').nth(1)).toContainText('Fixture Composer')
  await expect(labelList).not.toContainText('Unrelated Catalog Release')
  await page.getByRole('textbox', { name: 'Search label releases', exact: true }).fill('does not exist')
  await expect(page.getByText('No catalog releases match this view.', { exact: true })).toBeVisible()
  await page.getByRole('textbox', { name: 'Search label releases', exact: true }).fill('RELCAT001')
  await labelList.getByRole('link', { name: 'Fixture Catalog Release', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Fixture Catalog Release', exact: true, level: 1 })).toBeVisible()
  await page.getByRole('menuitem', { name: 'Releases', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Releases', exact: true, level: 1 })).toBeVisible()
  expect(writes).toEqual([]); expect(errors).toEqual([])
})

test('missing release errors are visible without a success-shaped empty page', async ({ page }) => {
  await page.goto('/admin/#/releases/missing/show')
  await page.getByLabel('API key').fill(key)
  await page.getByRole('button', { name: 'Connect', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: 'Catalog release was not found.' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Tracks', exact: true })).toHaveCount(0)
})

test('narrow touch Release view contains the table and keeps artwork management reachable', async ({ browser }) => {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true })
  try {
    const page = await context.newPage()
    await page.goto('/admin/#/releases/release-fixture/show')
    await page.getByLabel('API key').fill(key)
    await page.getByRole('button', { name: 'Connect', exact: true }).click()
    await expect(page.getByRole('table', { name: 'Catalog release tracks', exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
    const artwork = page.getByRole('button', { name: 'Change release artwork', exact: true })
    await expect(artwork.locator('.cover-action')).toHaveCSS('opacity', '1')
    await artwork.tap()
    const close = page.getByRole('button', { name: 'Close artwork', exact: true })
    await expect(close).toBeInViewport()
    await close.tap()
    await expect(page.getByRole('dialog')).toHaveCount(0)
  } finally {
    await context.close()
  }
})
