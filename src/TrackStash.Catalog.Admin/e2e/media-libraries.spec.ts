import { expect, test } from '@playwright/test'

test('Library settings persist renamed stable identity, add roots and update media names without restart', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/admin/#/media-libraries')
  await page.getByLabel('API key').fill('test-only-browser-key-not-a-production-secret')
  await page.getByRole('button', { name: 'Connect', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Media libraries', exact: true })).toBeVisible()
  const first = page.getByRole('region', { name: 'Library 1', exact: true })
  await expect(first.getByLabel('Library 1 name', { exact: true })).toHaveValue('JetDrive')
  await first.getByLabel('Library 1 name', { exact: true }).fill('My collection')
  const save = page.getByRole('button', { name: 'Save library settings', exact: true })
  await expect(save).toBeDisabled()
  await page.getByRole('checkbox', { name: 'I approve these library names and directory access settings' }).check()
  await save.click()
  await expect(page.getByRole('alert').filter({ hasText: 'Library settings saved' })).toBeVisible()
  await page.getByRole('button', { name: 'Reload saved settings (discard edits)', exact: true }).click()
  await expect(first.getByLabel('Library 1 name', { exact: true })).toHaveValue('My collection')
  await expect(first).toContainText('Stable ID: JetDrive')
  await page.getByRole('button', { name: 'Add library', exact: true }).click()
  const second = page.getByRole('region', { name: 'Library 2', exact: true })
  await second.getByLabel('Library 2 name', { exact: true }).fill('Future location')
  await second.getByLabel('Library 2 root directory', { exact: true }).fill('/unmounted-future-library')
  await expect(save).toBeDisabled()
  await page.getByRole('checkbox', { name: 'I approve these library names and directory access settings' }).check()
  await save.click()
  await expect(page.getByRole('alert').filter({ hasText: 'Library settings saved' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.getByRole('link', { name: 'Open Media', exact: true }).click()
  await page.getByRole('combobox', { name: 'Media library', exact: true }).click()
  await expect(page.getByRole('option', { name: 'My collection', exact: true })).toBeVisible()
  await expect(page.getByRole('option', { name: 'Future location', exact: true })).toBeVisible()
  await page.getByRole('option', { name: 'My collection', exact: true }).click()
  await expect(page.getByRole('table', { name: 'Media groups' })).toContainText('My collection')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
})

test('Library settings stale writes retain edits and require explicit reload', async ({ page }) => {
  await page.route('**/api/v1/media-libraries', async route => {
    if (route.request().method() === 'PATCH') {
      expect(route.request().headers()['if-match']).toBe('"original-settings"')
      await route.fulfill({ status: 412, json: { code: 'media_settings_changed', detail: 'Library settings changed; reload before saving.' } })
    } else await route.fulfill({ headers: { ETag: '"original-settings"' }, json: {
      version: 'v1', libraries: [{ id: 'stable', name: 'Original', root: '/test-library', enabled: true }],
    } })
  })
  await page.goto('/admin/#/media-libraries')
  await page.getByLabel('API key').fill('test-only-browser-key-not-a-production-secret')
  await page.getByRole('button', { name: 'Connect', exact: true }).click()
  await page.getByLabel('Library 1 name', { exact: true }).fill('Edited')
  await page.getByRole('checkbox', { name: 'I approve these library names and directory access settings' }).check()
  await page.getByRole('button', { name: 'Save library settings', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: 'Reload saved settings before saving again' })).toBeVisible()
  await expect(page.getByLabel('Library 1 name', { exact: true })).toHaveValue('Edited')
  await page.getByRole('button', { name: 'Reload saved settings (discard edits)', exact: true }).click()
  await expect(page.getByLabel('Library 1 name', { exact: true })).toHaveValue('Original')
})
