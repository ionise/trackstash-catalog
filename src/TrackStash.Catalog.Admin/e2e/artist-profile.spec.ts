  await page.getByRole('button', { name: 'Connect', exact: true }).click()
  await expect(page.getByRole('tab', { name: 'Details', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(portrait).toHaveAttribute('src', /^blob:/)
  await page.getByRole('button', { name: 'Edit Artist profile', exact: true }).click()
  await dialog.getByRole('textbox', { name: 'Biography', exact: true }).fill('Cancelled draft')
  await dialog.getByRole('button', { name: 'Cancel profile edits', exact: true }).click()
  await page.getByRole('button', { name: 'Change Artist artwork', exact: true }).click()
