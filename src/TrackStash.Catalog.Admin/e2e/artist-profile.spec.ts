  await page.keyboard.press('Tab')
  await expect(page.getByRole('tooltip')).toContainText('Recording credit:')
  await page.getByRole('tab', { name: 'Associations', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Collaborated with', exact: true })).toBeVisible()
  await expect(page.getByRole('tabpanel', { name: 'Associations', exact: true })).toContainText('No association counts have been calculated')
  await page.getByRole('tab', { name: 'Tracks', exact: true }).click()
  await expect(page.getByRole('table', { name: 'Artist track credits' }).getByRole('row')).toHaveCount(2)
  await page.getByRole('tab', { name: 'Details', exact: true }).click()
  await expect(page.getByText('Private curator notes', { exact: true })).toBeVisible()
