import { expect, test } from '@playwright/test'
import type { APIRequestContext, Page } from '@playwright/test'

const key = 'test-only-browser-key-not-a-production-secret'
const headers = { Authorization: `Bearer ${key}` }
async function label(request: APIRequestContext, name: string) {
  const response = await request.post('/api/v1/labels', { headers, data: { name } })
  expect(response.status()).toBe(201); return response.json()
}
async function group(request: APIRequestContext, name: string, kind = 'family') {
  const response = await request.post('/api/v1/label-groups', { headers, data: { name, kind } })
  expect(response.status()).toBe(201); return response.json()
}
async function login(page: Page, path: string) {
  await page.goto(`/admin/#${path}`)
  await page.getByLabel('API key').fill(key)
  await page.getByRole('button', { name: 'Connect', exact: true }).click()
  if (path.startsWith('/labels/')) await page.getByRole('tab', { name: 'Relationships', exact: true }).click()
}
async function addFromGroup(page: Page, name: string, id: string) {
  await page.getByRole('button', { name: 'Add member', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Review group membership' })
  await dialog.getByLabel('Find member label', { exact: true }).fill(name)
  await dialog.getByRole('button', { name: 'Search membership candidates', exact: true }).click()
  await dialog.getByRole('button', { name: `Select ${name} (${id})`, exact: true }).click()
  await dialog.getByRole('combobox', { name: 'Membership status', exact: true }).click()
  await page.getByRole('option', { name: 'Current', exact: true }).click()
  await dialog.getByRole('textbox', { name: /^Membership source/ }).fill('Official group site')
  await dialog.getByLabel('Since (latest period)', { exact: true }).fill('2020')
  await expect(dialog.getByRole('button', { name: 'Save membership', exact: true })).toBeDisabled()
  await dialog.getByRole('checkbox', { name: 'I have reviewed this membership and its evidence.' }).check()
  await dialog.getByRole('button', { name: 'Save membership', exact: true }).click()
  await expect(dialog).toBeHidden()
}

