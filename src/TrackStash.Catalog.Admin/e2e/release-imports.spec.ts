import { expect, test } from '@playwright/test'

const key = 'test-only-browser-key-not-a-production-secret'

test('saving retains other drafts, saved evidence, pagination and review reason, with a combined save action', async ({ page }) => {
  await page.goto('/admin/#/purchase-releases')
  await page.getByLabel('API key').fill(key)
  await page.getByRole('button', { name: 'Connect', exact: true }).click()
  await page.getByRole('button', { name: 'Inspect Inspector complete release (900)' }).click()
  const review = page.getByRole('region', { name: 'Immutable catalog import review' })
  await review.getByRole('button', { name: 'Create immutable import preview' }).click()
  const artist = review.getByRole('region', { name: 'Review artist 4907', exact: true })
  const other = review.getByRole('region', { name: 'Review artist 635680', exact: true })
  await artist.getByRole('textbox', { name: 'Note (optional)' }).fill('Accepted Kasey identity')
  await other.getByRole('combobox', { name: 'Identity action' }).click()
  await page.getByRole('option', { name: 'Retain an unresolved compound source identity' }).click()
  await other.getByRole('textbox', { name: 'Note (optional)' }).fill('Keep this draft for later review')
  await review.getByRole('textbox', { name: 'Import note (optional)' }).fill('Release rationale should survive saves')
  await review.getByRole('checkbox').check()
  await artist.getByRole('button', { name: 'Save decision', exact: true }).click()
  await expect(artist).toContainText('Current decision: create')
  await expect(artist.getByRole('textbox', { name: 'Note (optional)' })).toHaveValue('Accepted Kasey identity')
  await expect(other.getByRole('textbox', { name: 'Note (optional)' })).toHaveValue('Keep this draft for later review')
  await expect(other.getByRole('combobox', { name: 'Identity action' })).toContainText('unresolved compound')
  await expect(review.getByRole('checkbox')).not.toBeChecked()
  await expect(review.getByRole('textbox', { name: 'Import note (optional)' })).toHaveValue('Release rationale should survive saves')
  await review.getByRole('button', { name: 'Next identities', exact: true }).click()
  const track = review.getByRole('region', { name: 'Review recording 1006', exact: true })
  await track.getByRole('textbox', { name: 'Note (optional)' }).fill('Accepted recording version')
  await review.getByRole('button', { name: 'Next frozen tracks', exact: true }).click()
  let saves = 0
  await page.route('**/api/v1/release-import-previews', async route => {
    if (route.request().method() === 'POST' && ++saves === 2) {
      await route.fulfill({ status: 503, contentType: 'application/problem+json', body: JSON.stringify({ detail: 'Test save interrupted' }) })
    } else await route.continue()
  })
  await review.getByRole('button', { name: 'Save all edited decisions (2)', exact: true }).click()
  await expect(review.getByText(/Test save interrupted/)).toBeVisible()
  await expect(review.getByRole('button', { name: 'Save all edited decisions (1)', exact: true })).toBeEnabled()
  await expect(track.getByRole('textbox', { name: 'Note (optional)' })).toHaveValue('Accepted recording version')
  await page.unroute('**/api/v1/release-import-previews')
  await review.getByRole('button', { name: 'Save all edited decisions (1)', exact: true }).click()
  await expect(review.getByRole('button', { name: 'Save all edited decisions (0)', exact: true })).toBeDisabled()
  await expect(review.getByText('Identity page 2', { exact: true })).toBeVisible()
  await expect(review.getByText('Frozen track page 2', { exact: true })).toBeVisible()
  await expect(track.getByRole('textbox', { name: 'Note (optional)' })).toHaveValue('Accepted recording version')
  await review.getByRole('button', { name: 'Previous identities', exact: true }).click()
  await expect(other).toContainText('Current decision: unresolved')
  await expect(other.getByRole('textbox', { name: 'Note (optional)' })).toHaveValue('Keep this draft for later review')
})

test('bulk accept straightforward identities, confirm import, record a no-op without a note, and drop the admitted row once closed', async ({ page }) => {
  test.setTimeout(120_000)
  await page.goto('/admin/#/purchase-releases')
  await page.getByLabel('API key').fill(key)
  await page.getByRole('button', { name: 'Connect', exact: true }).click()
  await page.getByRole('switch', { name: 'Hide admitted releases' }).check()
  await page.getByRole('button', { name: 'Inspect Inspector complete release (900)' }).click()
  const review = page.getByRole('region', { name: 'Immutable catalog import review' })
  await review.getByRole('button', { name: 'Create immutable import preview' }).click()
  await expect(review.getByText('Apply blocked:')).toBeVisible()
  const apply = review.getByRole('button', { name: 'Apply reviewed catalog import', exact: true })
  await expect(apply).toBeDisabled()
  await review.getByRole('button', { name: 'Bulk accept straightforward identities', exact: true }).click()
  await expect(review.getByRole('progressbar', { name: 'Saving import review' })).toHaveCount(0)
  await expect(review.getByText('Apply blocked:')).toHaveCount(0)
  await expect(review.getByRole('textbox', { name: 'Import note (optional)' })).toHaveValue(/deliberately bulk-accepted/)
  await expect(apply).toBeDisabled()
  await review.getByRole('checkbox').check()
  await apply.click()
  await expect(review.getByText(/Saved import outcome for Release/)).toBeVisible()
  await expect(review).toContainText('4 Artists, 26 Recordings, 26 placements created')
  await review.getByRole('button', { name: 'Start a fresh preview (discard decisions)' }).click()
  await expect(review).toContainText('No-op.')
  await expect(review.getByRole('textbox', { name: 'Import note (optional)' })).toHaveValue('')
  await review.getByRole('checkbox').check()
  await review.getByRole('button', { name: 'Apply reviewed no-op' }).click()
  await expect(review.getByText(/Saved no-op outcome for Release/)).toBeVisible()
  await expect(review).toContainText('0 Artists, 0 Recordings, 0 placements created')
  await expect(review.getByText(/Saved no-op outcome for Release/)).toBeVisible()
  await page.getByRole('button', { name: 'Inspect Inspector complete release (900)' }).click()
  await expect(page.getByRole('button', { name: 'Inspect Inspector complete release (900)' })).toHaveCount(0)
  await page.getByRole('switch', { name: 'Hide admitted releases' }).uncheck()
  await page.getByRole('link', { name: 'Admitted - view catalog release for Inspector complete release' }).click()
  await expect(page.getByRole('heading', { name: 'Inspector complete release', exact: true, level: 1 })).toBeVisible()
  await expect(page.getByRole('table', { name: 'Catalog release tracks', exact: true }).getByRole('row')).toHaveCount(26)
})
